# Reference solution for t2-longest-unique-substring (trusted, server/learning only; never ship to the client).

def longest_unique_run(s):
    last, start, best = {}, 0, 0
    for i, ch in enumerate(s):
        if last.get(ch, -1) >= start:
            start = last[ch] + 1
        last[ch] = i
        best = max(best, i - start + 1)
    return best
